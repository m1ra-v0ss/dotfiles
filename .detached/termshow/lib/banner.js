/**
 * Render `text` as a 7-row banner.
 * @param {string} text
 * @param {object} [opts]
 * @param {boolean} [opts.doubleWidth=true]  render '#' as '██'
 * @param {string} [opts.fill='#']
 * @param {string} [opts.space=' ']
 * @returns {string[]} 7 lines
 */
function banner(text, opts = {}) {
  const doubleWidth = opts.doubleWidth !== false;
  const fill = opts.fill || '█';
  const gap = opts.gap !== undefined ? opts.gap : 1;
  const lines = ['', '', '', '', '', '', ''];
  const chars = String(text).toUpperCase().split('');
  for (let ci = 0; ci < chars.length; ci++) {
    const glyph = G[chars[ci]] || G['?'];
    for (let r = 0; r < 7; r++) {
      const row = glyph[r].replace(/#/g, fill).replace(/\./g, ' ');
      lines[r] += (doubleWidth ? row.replace(/(\S)/g, '$1$1') : row);
      if (ci < chars.length - 1) lines[r] += ' '.repeat(gap * (doubleWidth ? 2 : 1));
    }
  }
  // Equal row widths so frames compose; trailing spaces padded, not trimmed.
  const width = Math.max(...lines.map((l) => l.length));
  return lines.map((l) => l.padEnd(width));
}

